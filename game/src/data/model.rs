macro_rules! busts {
    ($folder:literal $(, $individual:ident)*) => {
        Some(Busts {
            generic: GenericBusts {
                neutral: AssetRef(concat!("busts/", $folder, "/neutral.png")),
                happy: AssetRef(concat!("busts/", $folder, "/happy.png")),
                sad: AssetRef(concat!("busts/", $folder, "/sad.png")),
                angry: AssetRef(concat!("busts/", $folder, "/angry.png")),
                surprised: AssetRef(concat!("busts/", $folder, "/surprised.png")),
                thinking: AssetRef(concat!("busts/", $folder, "/thinking.png")),
            },
            individual: &[$(ExpressionId::$individual),*],
        })
    };
}

